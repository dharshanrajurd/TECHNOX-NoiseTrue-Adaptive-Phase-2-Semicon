"""
Heavier augmentation on top of your existing RestorationDataset.

Adds, relative to the flip-only augmentation you trained the submitted
model with:
  - 90/180/270 rotations (lossless, no interpolation, safe to combine with flips)
  - light elastic deformation (same displacement field applied to GT at 2x
    scale, so the noisy/GT pair stays geometrically consistent)
  - a configurable fraction of samples replaced by synthetic degradation of
    that same sample's GT image, at randomized severity (see
    synthetic_degradation.py) -- widens the severity distribution the model
    trains on without touching the real provided pairs for the rest.

Everything falls back to exactly your original behavior when
augment=False (used for validation) or synth_prob=0.
"""

import os
import numpy as np
import torch
import torch.nn.functional as F
from torch.utils.data import Dataset

from src.synthetic_degradation import synthesize_degraded


def _elastic_displacement(h, w, alpha, sigma, device):
    """Smooth random displacement field, generated by blurring noise --
    avoids importing scipy/PIL just for this."""
    dx = torch.randn(1, 1, h, w, device=device)
    dy = torch.randn(1, 1, h, w, device=device)

    # cheap separable blur to smooth the noise into a coherent field
    k = max(3, int(sigma * 4) | 1)  # odd kernel size
    kernel = torch.ones(1, 1, 1, k, device=device) / k
    for d in (dx, dy):
        pass
    dx = F.conv2d(F.pad(dx, (k // 2, k // 2, 0, 0), mode="reflect"), kernel)
    dx = F.conv2d(F.pad(dx, (0, 0, k // 2, k // 2), mode="reflect"), kernel.transpose(2, 3))
    dy = F.conv2d(F.pad(dy, (k // 2, k // 2, 0, 0), mode="reflect"), kernel)
    dy = F.conv2d(F.pad(dy, (0, 0, k // 2, k // 2), mode="reflect"), kernel.transpose(2, 3))

    dx = dx * alpha
    dy = dy * alpha
    return dx.squeeze(0).squeeze(0), dy.squeeze(0).squeeze(0)  # (H, W) each


def _apply_elastic(img, dx, dy):
    """img: (1, H, W). dx/dy: (H, W) displacement in pixels."""
    _, h, w = img.shape
    device = img.device
    yy, xx = torch.meshgrid(
        torch.linspace(-1, 1, h, device=device),
        torch.linspace(-1, 1, w, device=device),
        indexing="ij",
    )
    grid_x = xx + (2.0 * dx / max(w - 1, 1))
    grid_y = yy + (2.0 * dy / max(h - 1, 1))
    grid = torch.stack([grid_x, grid_y], dim=-1).unsqueeze(0)  # (1, H, W, 2)
    out = F.grid_sample(
        img.unsqueeze(0), grid, mode="bilinear", padding_mode="reflection", align_corners=True
    )
    return out.squeeze(0)


class RestorationDatasetAugmentedV2(Dataset):
    """
    gt_folder / noisy_folder: same paired .npy layout as before.
    augment: master switch, same semantics as your original (True for
             training, False for validation -- flip it via dataset.augment).
    synth_prob: fraction of samples (when augment=True) that get replaced
                with a freshly synthesized degraded version of that sample's
                GT, at randomized severity, instead of the provided NoisyLR.
    elastic_prob: fraction of samples that get a light elastic warp.
    """

    def __init__(self, gt_folder, noisy_folder, augment=True,
                 synth_prob=0.3, elastic_prob=0.2,
                 elastic_alpha=4.0, elastic_sigma=6.0):
        self.gt_folder = gt_folder
        self.noisy_folder = noisy_folder
        self.files = sorted(os.listdir(gt_folder))
        self.augment = augment
        self.synth_prob = synth_prob
        self.elastic_prob = elastic_prob
        self.elastic_alpha = elastic_alpha
        self.elastic_sigma = elastic_sigma

    def __len__(self):
        return len(self.files)

    def __getitem__(self, idx):
        fname = self.files[idx]
        gt = np.load(os.path.join(self.gt_folder, fname)).astype(np.float32)
        noisy = np.load(os.path.join(self.noisy_folder, fname)).astype(np.float32)

        gt = torch.from_numpy(gt).unsqueeze(0)        # (1, H, W)
        noisy = torch.from_numpy(noisy).unsqueeze(0)  # (1, H/2, W/2)

        if self.augment:
            # --- synthetic re-degradation (severity augmentation) ---
            if torch.rand(1).item() < self.synth_prob:
                factor = gt.shape[-1] // noisy.shape[-1]
                noisy = synthesize_degraded(gt, downsample_factor=factor)

            # --- flips (unchanged from your original) ---
            if torch.rand(1).item() < 0.5:
                gt = torch.flip(gt, dims=[-1])
                noisy = torch.flip(noisy, dims=[-1])
            if torch.rand(1).item() < 0.5:
                gt = torch.flip(gt, dims=[-2])
                noisy = torch.flip(noisy, dims=[-2])

            # --- lossless 90-degree rotations ---
            k = torch.randint(0, 4, (1,)).item()
            if k > 0:
                gt = torch.rot90(gt, k, dims=[-2, -1])
                noisy = torch.rot90(noisy, k, dims=[-2, -1])

            # --- light elastic deformation, same field for both, scaled to
            #     the noisy image's coarser resolution ---
            if torch.rand(1).item() < self.elastic_prob:
                h, w = gt.shape[-2:]
                dx, dy = _elastic_displacement(h, w, self.elastic_alpha, self.elastic_sigma, gt.device)
                gt = _apply_elastic(gt, dx, dy)

                hn, wn = noisy.shape[-2:]
                scale = hn / h
                dx_n = F.interpolate(dx.view(1, 1, h, w), size=(hn, wn), mode="bilinear",
                                      align_corners=True).view(hn, wn) * scale
                dy_n = F.interpolate(dy.view(1, 1, h, w), size=(hn, wn), mode="bilinear",
                                      align_corners=True).view(hn, wn) * scale
                noisy = _apply_elastic(noisy, dx_n, dy_n)

        return noisy, gt
